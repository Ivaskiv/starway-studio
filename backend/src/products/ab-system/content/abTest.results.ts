export function interpolateFirstName(text: string, firstName?: string | null): string {
  const normalizedName = String(firstName ?? '').trim()
  if (!normalizedName) {
    return text
      .replace(/\{firstName\}/g, '')
      .replace(/^[\s,؛:—–-]+/, '')
  }

  return text.replace(/\{firstName\}/g, normalizedName)
}


function stringHash(value: string) {
  let hash = 0
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash * 31 + value.charCodeAt(index)) >>> 0
  }
  return hash
}

export function pickTemplate(intent: Intent, seed: string): MentorTemplate {
  const pool = templates[intent]
  const index = stringHash(`${intent}:${seed}`) % pool.length
  return pool[index]
}

// ============================================================================
// WHEEL ANALYSIS PROMPT (модуль A)
// ============================================================================

export function buildWheelAnalysisPrompt(assessment: WheelAssessment): string {
  const { scores, weakestSphere, focusSphere } = assessment;
  
  return `
ЗАВДАННЯ: Проаналізуй колесо балансу користувача.

ДАНІ:
${Object.entries(scores).map(([sphere, score]) => `- ${sphere}: ${score}/10`).join('\n')}

Найслабша сфера: ${weakestSphere}
Сфера фокусу: ${focusSphere}

ВИМОГИ ДО АНАЛІЗУ:
1. Коротко (2-3 речення)
2. Без рекомендацій — тільки фіксація перекосу
3. Вкажи різницю між найсильнішою та найслабшою сферою
4. Опиши системний вплив перекосу

ФОРМАТ:
Перекіс: [різниця між сферами]
Системний вплив: [як слабкість в одній сфері впливає на інші]
Фокус: [що фіксувати в щоденному циклі]
`.trim();
}

// ============================================================================
// DAILY MIRROR PROMPT (модуль B)
// ============================================================================

export function buildDailyMirrorPrompt(entries: DailyCycleEntry[]): string {
  const states = entries.map(e => e.state);
  const drains = entries.map(e => e.drain);
  const choices = entries.map(e => e.choice);
  
  return `
ЗАВДАННЯ: Дзеркало щоденних записів.

ПЕРІОД: ${entries.length} днів

ДАНІ:
Стани: ${states.join(', ')}
Зливи: ${drains.join(', ')}
Вибори: ${choices.join(', ')}

ВИМОГИ:
1. Виявити повторюваний стан (якщо є)
2. Виявити головний злив
3. Фіксувати, якщо вибір 'confirmed_old' переважає
4. Без мотивації — тільки факти

ФОРМАТ:
Повтор стану: [стан] - [кількість разів]
Головний злив: [злив] - [кількість разів]
Вибір: [статистика chose_new vs confirmed_old]
Системний висновок: [1 речення про напрямок руху]
`.trim();
}

// ============================================================================
// TRIAL MIRROR PROMPTS (day 4 та final)
// ============================================================================

export function buildTrialMirrorPrompt(
  type: 'day4' | 'final',
  entries: DailyCycleEntry[],
  wheelData?: { weakestSphere: string; focusSphere: string }
): string {
  const basePrompt = `
ЗАВДАННЯ: ${type === 'day4' ? 'Дзеркало 1 (день 4 trial)' : 'Фінальне дзеркало (день 7 trial)'}

ДАНІ:
${entries.map((e, i) => `День ${i + 1}: Стан=${e.state}, Злив=${e.drain}, Вибір=${e.choice}`).join('\n')}

${wheelData ? `Колесо балансу: Слабка сфера=${wheelData.weakestSphere}, Фокус=${wheelData.focusSphere}` : ''}

ВИМОГИ:
1. Зведення повторів станів
2. Головний злив
3. ${wheelData ? 'Звʼязок зливу зі слабкою сферою колеса' : 'Загальний патерн'}
4. ${type === 'final' ? 'Контраст "до AI / з AI" — що змінилось за 7 днів' : ''}
5. Без мотивації

ФОРМАТ:
${type === 'day4' ? `
Повтор станів: [...]
Головний злив: [...]
Сфера перекосу: [...]
` : `
Повтор станів: [...]
Головний злив: [...]
Контраст до/з AI: [що було / що стало]
Накопичення стабільності: [кількість днів]
Наступний крок: [підписка для повного доступу]
`}
`.trim();

  return basePrompt;
}

// ============================================================================
// VISION GUIDE PROMPT (модуль D - paid)
// ============================================================================

export function buildVisionGuidePrompt(step: 'intro' | 'question1' | 'question2' | 'question3' | 'summary'): string {
  const prompts = {
    intro: `
ЗАВДАННЯ: Введення в процес формування бачення.

КОНТЕКСТ: Користувач оплатив підписку, онбординг етап 'vision' (2-12 год).

ВИМОГИ:
1. Коротко пояснити: бачення — це не мрії, а конкретика
2. Без мотивації, без "ти молодець"
3. Підготувати до 3 питань

ФОРМАТ:
Бачення — це не "хочу бути щасливою", а точка Б, яку ти можеш описати конкретно.
Зараз три питання. Відповідай чесно, без фантазій.
`,
    question1: `
ПИТАННЯ 1: Як ти хочеш жити?

ВИМОГИ ДО ВІДПОВІДІ:
- Не абстракції ("бути щасливою")
- Конкретика (розклад дня, заняття, стосунки, дохід)
- Мінімум 50 символів

Постав питання користувачу без додаткових пояснень.
`,
    question2: `
ПИТАННЯ 2: Що більше не норма в твоєму житті?

ВИМОГИ:
- Що саме ти більше не готова терпіти
- Конкретні ситуації, стани, поведінка
- Мінімум 30 символів

Постав питання без пояснень.
`,
    question3: `
ПИТАННЯ 3: Опиши точку Б — де ти хочеш бути через 6 місяців.

ВИМОГИ:
- Конкретні зміни (робота, дохід, стосунки, стан)
- Вимірні показники
- Мінімум 50 символів

Постав питання.
`,
    summary: `
ЗАВДАННЯ: Сформувати vision_statement на основі відповідей користувача.

ВИМОГИ:
1. Об'єднати всі три відповіді в одне чітке твердження
2. Без прикрас, без мотивації
3. Формат: "Точка Б: [конкретний опис життя через 6 міс]. Більше не норма: [що відкидається]. Шлях: [як саме хочу жити]."
4. Максимум 4 речення

Видай готовий vision_statement.
`
  };

  return prompts[step];
}

